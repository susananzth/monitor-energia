CREATE TABLE dispositivo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL,
    api_key_hash  VARCHAR(64)  NOT NULL UNIQUE,
    creado_en     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE sesion_medicion (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_id            BIGINT NOT NULL REFERENCES dispositivo (id),
    carga_declarada           VARCHAR(200) NOT NULL,
    v_ref                     DOUBLE PRECISION NOT NULL DEFAULT 220,
    factor_potencia_supuesto  DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    inicio                    TIMESTAMP WITH TIME ZONE NOT NULL,
    fin                       TIMESTAMP WITH TIME ZONE,
    notas                     VARCHAR(1000)
);
CREATE INDEX idx_sesion_dispositivo ON sesion_medicion (dispositivo_id, fin);

CREATE TABLE lectura (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id               BIGINT NOT NULL REFERENCES sesion_medicion (id),
    timestamp_dispositivo   TIMESTAMP WITH TIME ZONE,
    timestamp_servidor      TIMESTAMP WITH TIME ZONE NOT NULL,
    i_rms                   DOUBLE PRECISION NOT NULL,
    p_est                   DOUBLE PRECISION NOT NULL,
    intervalo_s             DOUBLE PRECISION NOT NULL,
    energia_acumulada_kwh   DOUBLE PRECISION NOT NULL,
    secuencia               BIGINT NOT NULL,
    CONSTRAINT uq_lectura_sesion_secuencia UNIQUE (sesion_id, secuencia)
);
CREATE INDEX idx_lectura_sesion_tiempo ON lectura (sesion_id, timestamp_servidor);

CREATE TABLE lectura_referencia (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id        BIGINT NOT NULL REFERENCES sesion_medicion (id),
    marca_tiempo     TIMESTAMP WITH TIME ZONE NOT NULL,
    i_pinza          DOUBLE PRECISION NOT NULL,
    i_prototipo      DOUBLE PRECISION NOT NULL,
    diferencia_abs   DOUBLE PRECISION NOT NULL,
    diferencia_pct   DOUBLE PRECISION NOT NULL
);
CREATE INDEX idx_referencia_sesion ON lectura_referencia (sesion_id);
