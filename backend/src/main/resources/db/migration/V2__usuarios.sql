CREATE TABLE usuario (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario        VARCHAR(50)  NOT NULL UNIQUE,
    nombre         VARCHAR(100) NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    rol            VARCHAR(20)  NOT NULL,
    activo         BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en      TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Tokens de acceso: solo se guarda el hash SHA-256; el token en claro lo tiene el navegador.
CREATE TABLE token_acceso (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    creado_en   TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_en   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_token_usuario ON token_acceso (usuario_id);
CREATE INDEX idx_token_expira ON token_acceso (expira_en);
